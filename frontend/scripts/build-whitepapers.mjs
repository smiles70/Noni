/**
 * build-whitepapers.mjs — renders markdown whitepapers to branded PDFs.
 *
 * Reads docs/marketing/*.md (relative to repo root), converts to styled
 * HTML, and prints to PDF via headless Chromium (Playwright — already a
 * devDependency). Output: frontend/public/whitepapers/<slug>.pdf
 *
 * Usage: node scripts/build-whitepapers.mjs
 * Requires: npx playwright install chromium (one-time).
 * NOT wired into CI build — PDFs are committed artifacts; regenerate
 * locally when a paper changes.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, basename } from "node:path";
import { chromium } from "playwright";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..");
const SRC = join(ROOT, "docs", "marketing");
const OUT = join(here, "..", "public", "whitepapers");

const PAPERS = [
  { file: "the-ai-gap-whitepaper.md", slug: "the-ai-gap" },
  { file: "geragogy-whitepaper.md", slug: "geragogy-the-key-to-learning" },
];

// Minimal markdown → HTML for these documents' vocabulary.
function md2html(md) {
  const esc = (s) =>
    s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const inline = (s) =>
    esc(s)
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/\*([^*]+)\*/g, "<em>$1</em>")
      .replace(
        /\[([^\]]+)\]\((https?:[^)]+)\)/g,
        '<a href="$2">$1</a>',
      )
      .replace(/(https?:\/\/[^\s<]+)/g, '<a href="$1">$1</a>');

  const lines = md.split("\n");
  let html = "";
  let inList = false;
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (/^[-*] |^\d+\. /.test(line)) {
      if (!inList) {
        html += "<ul>";
        inList = true;
      }
      html += `<li>${inline(line.replace(/^([-*]|\d+\.)\s+/, ""))}</li>`;
      continue;
    }
    if (inList) {
      html += "</ul>";
      inList = false;
    }
    if (!line) continue;
    if (line === "---") html += "<hr>";
    else if (line.startsWith("### ")) html += `<h3>${inline(line.slice(4))}</h3>`;
    else if (line.startsWith("## ")) html += `<h2>${inline(line.slice(3))}</h2>`;
    else if (line.startsWith("# ")) html += `<h1>${inline(line.slice(2))}</h1>`;
    else html += `<p>${inline(line)}</p>`;
  }
  if (inList) html += "</ul>";
  return html;
}

const CSS = `
  @page { margin: 2.2cm 2.4cm; }
  body {
    font-family: "Source Sans 3", "Inter", -apple-system, "Segoe UI", sans-serif;
    color: #222222; background: #FAFAF8;
    font-size: 11.5pt; line-height: 1.55; max-width: 720px; margin: 0 auto;
  }
  h1 { font-size: 26pt; line-height: 1.2; margin: 0 0 4px; }
  h2 { font-size: 15pt; margin: 26px 0 8px; color: #222222; }
  h3 { font-size: 12.5pt; margin: 18px 0 6px; }
  p { margin: 0 0 10px; }
  ul { margin: 0 0 12px; padding-left: 22px; }
  li { margin-bottom: 6px; }
  a { color: #4A6FA5; text-decoration: none; word-break: break-all; }
  hr { border: none; border-top: 1px solid #B0B0B0; margin: 26px 0; }
  strong { color: #1a1a1a; }
  h1 + h3 { color: #4A6D5C; font-weight: 600; }
`;

mkdirSync(OUT, { recursive: true });

const browser = await chromium.launch();
const page = await browser.newPage();

for (const { file, slug } of PAPERS) {
  const md = readFileSync(join(SRC, file), "utf8");
  const html = `<!doctype html><html><head><meta charset="utf-8"><style>${CSS}</style></head><body>${md2html(md)}</body></html>`;
  await page.setContent(html, { waitUntil: "load" });
  const out = join(OUT, `${slug}.pdf`);
  await page.pdf({ path: out, format: "A4", printBackground: true });
  console.log(`built ${basename(out)}`);
}

await browser.close();
writeFileSync(
  join(OUT, "README.txt"),
  "Generated by scripts/build-whitepapers.mjs — regenerate after editing docs/marketing/*.md\n",
);
console.log("done");
